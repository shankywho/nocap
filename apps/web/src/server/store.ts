import { createHash, randomBytes } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { Receipt } from "@nocap/core";
import { PrismaStore, type PrismaLike } from "./prismaStore";

export interface StoredReceipt {
  id: string;
  createdAt: string;
  source: "CLI" | "PR" | "MCP" | "HOOK" | "DEMO";
  isExample: boolean;
  headline: string;
  deleteTokenHash: string;
  receipt: Receipt;
}

export interface ReceiptStore {
  put(r: StoredReceipt): Promise<void>;
  get(id: string): Promise<StoredReceipt | null>;
  remove(id: string): Promise<boolean>;
  examples(): Promise<StoredReceipt[]>;
  chain(chainId: string): Promise<StoredReceipt[]>;
  published(): Promise<StoredReceipt[]>;
}

/** In-memory store used for mock mode and tests. Same interface a Prisma store implements. */
export class MemoryStore implements ReceiptStore {
  private rows = new Map<string, StoredReceipt>();
  async put(r: StoredReceipt) {
    this.rows.set(r.id, r);
  }
  async get(id: string) {
    return this.rows.get(id) ?? null;
  }
  async remove(id: string) {
    return this.rows.delete(id);
  }
  private all() {
    return [...this.rows.values()].sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  }
  async examples() {
    return this.all().filter((r) => r.isExample);
  }
  async chain(chainId: string) {
    return this.all()
      .filter((r) => r.receipt.chain.chainId === chainId)
      .sort((a, b) => a.receipt.chain.attempt - b.receipt.chain.attempt);
  }
  async published() {
    return this.all().filter((r) => !r.isExample);
  }
}

const g = globalThis as unknown as { __nocapStore?: ReceiptStore; __nocapDb?: "ok" | "memory" | "down" };

/** Memory store, or Postgres through Prisma when DATABASE_URL is set and MOCK_EXTERNALS is not true. Falls back to memory if the client is unavailable. */
class LazyStore implements ReceiptStore {
  private ready: Promise<ReceiptStore> | null = null;
  private inner(): Promise<ReceiptStore> {
    return (this.ready ??= (async () => {
      const mem = new MemoryStore();
      if (process.env.DATABASE_URL && process.env.MOCK_EXTERNALS === "false") {
        try {
          const name = "@prisma/client";
          const mod = (await import(/* webpackIgnore: true */ name)) as { PrismaClient: new () => PrismaLike };
          const store = new PrismaStore(new mod.PrismaClient());
          seedExamples(mem);
          for (const ex of await mem.examples()) await store.put(ex);
          g.__nocapDb = "ok";
          return store;
        } catch {
          g.__nocapDb = "down";
        }
      } else {
        g.__nocapDb = "memory";
      }
      seedExamples(mem);
      return mem;
    })());
  }
  async put(r: StoredReceipt) { return (await this.inner()).put(r); }
  async get(id: string) { return (await this.inner()).get(id); }
  async remove(id: string) { return (await this.inner()).remove(id); }
  async examples() { return (await this.inner()).examples(); }
  async chain(chainId: string) { return (await this.inner()).chain(chainId); }
  async published() { return (await this.inner()).published(); }
}

export function getStore(): ReceiptStore {
  return (g.__nocapStore ??= new LazyStore());
}
export function dbStatus(): "ok" | "memory" | "down" {
  return g.__nocapDb ?? (process.env.DATABASE_URL && process.env.MOCK_EXTERNALS === "false" ? "down" : "memory");
}
export function setStore(s: ReceiptStore) {
  g.__nocapStore = s;
}

function examplesDir(): string | null {
  for (const dir of [resolve(process.cwd(), "examples"), resolve(process.cwd(), "../../examples")]) if (existsSync(dir)) return dir;
  return null;
}

/** Loads examples/*.json (generated by `pnpm examples:generate`) as isExample receipts with fixed ids. */
export function seedExamples(store: MemoryStore, dir = examplesDir()) {
  if (!dir) return;
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const receipt = Receipt.parse(JSON.parse(readFileSync(join(dir, file), "utf8")));
    void store.put({
      id: receipt.id,
      createdAt: receipt.createdAt,
      source: "DEMO",
      isExample: true,
      headline: headlineOf(receipt),
      deleteTokenHash: "",
      receipt,
    });
  }
}

export const newId = () => randomBytes(8).toString("base64url").slice(0, 10);
export const hashToken = (t: string) => createHash("sha256").update(t).digest("hex");

export function headlineOf(r: Receipt): string {
  const bad = r.claims.find((c) => c.verdict.status === "contradicted");
  const text = bad ? `✗ ${bad.claim.quote}` : `${r.totals.verified} claims verified`;
  return text.slice(0, 140);
}
